import { afterAll, describe, expect, test } from "bun:test"
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "fs"
import { tmpdir } from "os"
import { join } from "path"
import {
  auditSkills,
  parseFrontmatter,
  pruneOrphanReplicas,
  removeGeneratedReplica,
  scanSkills,
  skillRoots,
  type SkillRoot,
} from "./skill-audit"

const MARK = "<!-- AUTO-GENERATED by iris playbook sync — do not edit -->"
const tmp = mkdtempSync(join(tmpdir(), "skill-audit-"))
afterAll(() => rmSync(tmp, { recursive: true, force: true }))

function put(file: string, text: string) {
  mkdirSync(join(file, ".."), { recursive: true })
  writeFileSync(file, text)
}
const skill = (name: string, desc: string | null, generated = false, extra = "") =>
  `---\nname: ${name}\n${desc === null ? "" : `description: ${desc}\n`}---\n${generated ? MARK + "\n" : ""}\nBody ${extra}\n`

describe("parseFrontmatter mirrors the IRIS app's tolerant parser", () => {
  test("an unquoted colon in a value is accepted (the app retries as a block scalar)", () => {
    const fm = parseFrontmatter("---\nname: x\ndescription: Ship it: safely\n---\nbody")
    expect(fm.description).toBe("Ship it: safely")
  })
})

describe("auditSkills", () => {
  const home = join(tmp, "home")
  const proj = join(home, "work", "proj")
  const H = join(home, ".claude", "skills")
  const P = join(proj, ".claude", "skills")
  put(join(H, "ok", "SKILL.md"), skill("ok", "Fine"))
  put(join(H, "nofm", "SKILL.md"), "# no frontmatter\n")
  put(join(H, "noname", "SKILL.md"), "---\ndescription: d\n---\nx")
  put(join(H, "nodesc", "SKILL.md"), skill("nodesc", null))
  put(join(H, "emptydesc", "SKILL.md"), skill("emptydesc", '""'))
  put(join(H, "Bad_Id", "SKILL.md"), skill("Bad_Id", "d"))
  put(join(H, "folder", "SKILL.md"), skill("other-name", "d"))
  put(join(H, "lower", "skill.md"), skill("lower", "d"))
  // same id, different text, in two scopes
  put(join(H, "dup", "SKILL.md"), skill("dup", "d", true, "global"))
  put(join(P, "dup", "SKILL.md"), skill("dup", "d", true, "project"))
  // same id, identical text
  put(join(H, "same", "SKILL.md"), skill("same", "d"))
  put(join(P, "same", "SKILL.md"), skill("same", "d"))
  // a generated replica whose playbook is gone, and one whose playbook exists
  put(join(P, "gone", "SKILL.md"), skill("gone", "d", true))
  put(join(P, "kept", "SKILL.md"), skill("kept", "d", true))
  put(join(proj, ".iris", "playbooks", "kept", "PLAYBOOK.md"), "---\nname: kept\n---\n")
  // the same shape, hand-written: never an orphan
  put(join(P, "mine", "SKILL.md"), skill("mine", "d"))
  mkdirSync(join(proj, ".git"), { recursive: true })

  const roots = skillRoots({ cwd: proj, home, stop: proj })
  const files = scanSkills(roots)
  const findings = auditSkills(files)
  const codes = (id: string | null, file?: string) =>
    findings.filter((f) => f.id === id && (!file || f.file.includes(file))).map((f) => f.code)

  test("roots are the app's, global before project", () => {
    expect(roots.map((r) => r.dir)).toEqual([H, P])
  })
  test("no frontmatter and no name are errors — the app drops both", () => {
    expect(findings.find((f) => f.file.includes("nofm"))?.code).toBe("unparseable")
    expect(findings.find((f) => f.file.includes("noname"))?.code).toBe("no-name")
  })
  test("missing and empty descriptions are errors", () => {
    expect(codes("nodesc")).toContain("no-description")
    expect(codes("emptydesc")).toContain("empty-description")
  })
  test("a non-portable id is an error; folder ≠ name is a warning", () => {
    expect(codes("Bad_Id")).toContain("invalid-id")
    expect(codes("other-name")).toContain("name-not-folder")
  })
  test("skill.md (lowercase) is found and flagged for Linux", () => {
    expect(codes("lower")).toContain("lowercase-filename")
  })
  test("different copies of one id are an error; identical copies are only info", () => {
    expect(findings.find((f) => f.id === "dup")?.level).toBe("error")
    expect(findings.find((f) => f.id === "dup")?.code).toBe("shadowed")
    expect(findings.find((f) => f.id === "same")?.level).toBe("info")
  })
  test("orphans: only a GENERATED replica whose playbook is gone", () => {
    expect(codes("gone")).toContain("orphan")
    expect(codes("kept")).not.toContain("orphan")
    expect(codes("mine")).not.toContain("orphan")
  })
  test("a healthy skill has no findings", () => {
    expect(codes("ok")).toEqual([])
  })
  test("keep: a playbook the loader still finds is never an orphan", () => {
    expect(auditSkills(files, new Set(["gone"])).some((f) => f.code === "orphan")).toBe(false)
  })
})

describe("pruneOrphanReplicas / removeGeneratedReplica", () => {
  const root = join(tmp, "prune")
  const S = join(root, ".claude", "skills")
  put(join(S, "gone", "SKILL.md"), skill("gone", "d", true))
  put(join(S, "gone-with-scripts", "SKILL.md"), skill("gone-with-scripts", "d", true))
  put(join(S, "gone-with-scripts", "run.sh"), "echo")
  put(join(S, "renamed-now", "SKILL.md"), skill("renamed-now", "d", true))
  put(join(S, "hand", "SKILL.md"), skill("hand", "d"))
  put(join(S, "alive", "SKILL.md"), skill("alive", "d", true))
  put(join(root, ".iris", "playbooks", "alive", "PLAYBOOK.md"), "x")
  const real = join(root, "elsewhere", "linked")
  put(join(real, "SKILL.md"), skill("linked", "d", true))
  symlinkSync(real, join(S, "linked"))

  const removed = pruneOrphanReplicas(S, new Set(["renamed-now"]))

  test("removes generated orphans, and only their SKILL.md", () => {
    expect(removed.sort()).toEqual(["gone", "gone-with-scripts"])
    expect(existsSync(join(S, "gone"))).toBe(false)
    expect(existsSync(join(S, "gone-with-scripts", "run.sh"))).toBe(true)
  })
  test("never a hand-written skill, a symlinked one, a kept one, or one with a playbook", () => {
    for (const d of ["hand", "linked", "renamed-now", "alive"]) expect(existsSync(join(S, d, "SKILL.md"))).toBe(true)
    expect(readFileSync(join(real, "SKILL.md"), "utf8")).toContain("linked")
  })
  test("removeGeneratedReplica refuses hand-written and symlinked skills", () => {
    expect(removeGeneratedReplica(S, "hand")).toBe("hand-written")
    expect(removeGeneratedReplica(S, "linked")).toBe("symlink")
    expect(removeGeneratedReplica(S, "nope")).toBe("absent")
    expect(removeGeneratedReplica(S, "alive")).toBe("removed")
    expect(existsSync(join(S, "alive"))).toBe(false)
  })
})

describe("skillRoots", () => {
  test("walks .claude/.agents/.opencode from cwd up to the stop, after the home roots", () => {
    const home = join(tmp, "h2")
    const a = join(home, "a")
    const b = join(a, "b")
    for (const d of [join(home, ".claude", "skills"), join(a, ".agents", "skills"), join(b, ".claude", "skills"), join(b, ".opencode", "skills"), join(home, ".config", "opencode", "skill")])
      mkdirSync(d, { recursive: true })
    const roots = skillRoots({ cwd: b, home, stop: a }).map((r: SkillRoot) => r.dir)
    expect(roots).toEqual([
      join(home, ".claude", "skills"),
      join(b, ".claude", "skills"),
      join(a, ".agents", "skills"),
      join(home, ".config", "opencode", "skill"),
      join(b, ".opencode", "skills"),
    ])
  })
})
