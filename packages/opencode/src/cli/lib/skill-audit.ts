// ============================================================================
// What the IRIS Desktop app (OpenCode 1.18) will actually make of the skills on this machine.
//
// `iris playbook doctor` checks playbooks. This checks the OTHER half — the SKILL.md replicas the
// app and Claude Code read — because every way a skill goes missing there is silent:
//
//   - no frontmatter, or no string `name`      → 1.18 drops the file; Claude Code still lists it
//   - no / empty description                   → never offered to the model
//   - an ID that is not lowercase-hyphen        → Claude Code refuses it; 1.18 accepts it
//   - the same ID in two places, different text → 1.18.117 picks one AT RANDOM per start
//                                                  (measured: four runs, four different winners)
//   - a generated replica whose playbook is gone → a skill for a procedure that no longer exists
//   - `skill.md` instead of `SKILL.md`           → found on macOS, missing on Linux
//
// Roots are the ones 1.18.23 scans (packages/opencode/src/skill/index.ts there), in its order.
// ============================================================================
import nodePath from "path"
import { existsSync, lstatSync, readdirSync, readFileSync, rmdirSync, statSync, unlinkSync } from "fs"
import { createHash } from "crypto"
import matter from "gray-matter"
import { SKILL_DESCRIPTION_MAX, isValidSkillId } from "./skill-replica"

export const SKILL_GENERATED_MARKER_TEXT = "AUTO-GENERATED by iris playbook sync"

/**
 * Frontmatter as the IRIS app 1.18 reads it: gray-matter, then — for the unquoted colons other
 * agents tolerate — the same block-scalar retry as its `ConfigMarkdown.sanitize`. Mirrors it so a
 * file the app accepts is never reported as dropped.
 */
export function parseFrontmatter(text: string): Record<string, unknown> {
  try {
    return matter(text).data ?? {}
  } catch {
    return matter(sanitizeFrontmatter(text)).data ?? {}
  }
}

export function sanitizeFrontmatter(content: string): string {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---/)
  if (!match) return content
  const frontmatter = match[1]
  const result = frontmatter.split(/\r?\n/).flatMap((line) => {
    if (line.trim().startsWith("#") || line.trim() === "" || /^\s+/.test(line)) return [line]
    const entry = line.match(/^([a-zA-Z_][a-zA-Z0-9_]*)\s*:\s*(.*)$/)
    if (!entry) return [line]
    const value = entry[2].trim()
    if (value === "" || value === ">" || value === "|" || value.startsWith('"') || value.startsWith("'")) return [line]
    if (!value.includes(":")) return [line]
    return [`${entry[1]}: |-`, `  ${value}`]
  })
  return content.replace(frontmatter, () => result.join("\n"))
}

export interface SkillRoot {
  label: string
  /** A directory whose subfolders hold `<id>/SKILL.md`. */
  dir: string
}

/** The skill roots 1.18.23 reads from `cwd`, in its discovery order (later = registered later). */
export function skillRoots(opts: { cwd: string; home: string; stop?: string | null; exists?: (p: string) => boolean }): SkillRoot[] {
  const exists = opts.exists ?? existsSync
  const p = nodePath
  const out: SkillRoot[] = [
    { label: "~/.claude/skills", dir: p.join(opts.home, ".claude", "skills") },
    { label: "~/.agents/skills", dir: p.join(opts.home, ".agents", "skills") },
  ]
  // Project roots: every .claude / .agents from cwd up to the project root (not past home).
  const ups: string[] = []
  let cur = p.resolve(opts.cwd)
  const home = p.resolve(opts.home)
  while (cur !== home) {
    ups.push(cur)
    if (opts.stop && p.resolve(opts.stop) === cur) break
    const parent = p.dirname(cur)
    if (parent === cur) break
    cur = parent
  }
  for (const d of ups) {
    for (const ext of [".claude", ".agents"]) out.push({ label: p.join(p.relative(opts.cwd, d) || ".", ext, "skills"), dir: p.join(d, ext, "skills") })
  }
  for (const s of ["skill", "skills"]) out.push({ label: `~/.config/opencode/${s}`, dir: p.join(opts.home, ".config", "opencode", s) })
  for (const d of ups) for (const s of ["skill", "skills"]) out.push({ label: p.join(p.relative(opts.cwd, d) || ".", ".opencode", s), dir: p.join(d, ".opencode", s) })
  // De-dupe (cwd == home edge cases) while keeping order, and keep only roots that exist.
  const seen = new Set<string>()
  return out.filter((r) => {
    if (seen.has(r.dir)) return false
    seen.add(r.dir)
    return exists(r.dir)
  })
}

export interface SkillFile {
  root: SkillRoot
  file: string
  /** Folder holding the file, relative to the root (`foo`, or `synced/x/foo` when nested). */
  rel: string
  name: string | null
  description: string | null | undefined
  parseError: string | null
  generated: boolean
  sha: string
}

function walk(dir: string, depth: number, out: string[]) {
  if (depth > 6) return
  let entries: string[]
  try {
    entries = readdirSync(dir)
  } catch {
    return
  }
  for (const e of entries) {
    const f = nodePath.join(dir, e)
    let st
    try {
      st = statSync(f) // follows symlinks, as 1.18 does
    } catch {
      continue
    }
    if (st.isDirectory()) walk(f, depth + 1, out)
    else if (e.toLowerCase() === "skill.md" && depth > 0) out.push(f)
  }
}

/** Parse just enough frontmatter to know what 1.18 will key the skill by. */
export function readSkillFile(file: string, root: SkillRoot, parse: (src: string) => any = parseFrontmatter): SkillFile {
  let text = ""
  try {
    text = readFileSync(file, "utf8")
  } catch {}
  const rel = nodePath.relative(root.dir, nodePath.dirname(file))
  const base = { root, file, rel, generated: text.includes(SKILL_GENERATED_MARKER_TEXT), sha: createHash("sha1").update(text).digest("hex") }
  if (!/^---\r?\n/.test(text)) return { ...base, name: null, description: undefined, parseError: "no frontmatter (the file must start with ---)" }
  try {
    const fm = parse(text) ?? {}
    return {
      ...base,
      name: typeof fm.name === "string" ? fm.name : null,
      description: fm.description === undefined ? undefined : typeof fm.description === "string" ? fm.description : null,
      parseError: null,
    }
  } catch (e: any) {
    return { ...base, name: null, description: undefined, parseError: `frontmatter does not parse: ${String(e?.reason ?? e?.message ?? e).split("\n")[0]}` }
  }
}

export function scanSkills(roots: SkillRoot[], parse: (src: string) => any = parseFrontmatter): SkillFile[] {
  const out: SkillFile[] = []
  for (const root of roots) {
    const files: string[] = []
    walk(root.dir, 0, files)
    for (const f of files.sort()) out.push(readSkillFile(f, root, parse))
  }
  return out
}

export type FindingCode =
  | "unparseable"
  | "no-name"
  | "invalid-id"
  | "no-description"
  | "empty-description"
  | "long-description"
  | "name-not-folder"
  | "lowercase-filename"
  | "shadowed"
  | "shadowed-identical"
  | "orphan"

export interface Finding {
  level: "error" | "warning" | "info"
  code: FindingCode
  id: string | null
  file: string
  message: string
}

/**
 * The `.iris/playbooks/<name>/PLAYBOOK.md` a generated replica in `skillsDir` was made from —
 * the replica's folder is the playbook name, and a skills dir sits beside its playbooks dir.
 */
export function sourcePlaybookFor(skillsDir: string, folder: string): string {
  return nodePath.join(nodePath.dirname(nodePath.dirname(skillsDir)), ".iris", "playbooks", folder, "PLAYBOOK.md")
}

/** A generated replica (never a hand-written skill) whose playbook is gone. */
export function isOrphanReplica(f: SkillFile, keep?: Set<string>): boolean {
  if (!f.generated) return false
  if (f.rel.includes(nodePath.sep) || f.rel.includes("/")) return false // only top-level replicas are ours
  if (keep?.has(f.rel)) return false
  // A PLAYBOOK.md in the same folder is the source, wherever that folder is (legacy layout).
  if (existsSync(nodePath.join(nodePath.dirname(f.file), "PLAYBOOK.md"))) return false
  try {
    if (lstatSync(nodePath.dirname(f.file)).isSymbolicLink()) return false // a link points at someone's checkout
  } catch {
    return false
  }
  return !existsSync(sourcePlaybookFor(f.root.dir, f.rel))
}

/** `keep`: ids that still have a playbook somewhere the loader finds — never called orphans. */
export function auditSkills(files: SkillFile[], keep?: Set<string>): Finding[] {
  const out: Finding[] = []
  const byId = new Map<string, SkillFile[]>()
  for (const f of files) {
    const at = f.file
    if (nodePath.basename(f.file) !== "SKILL.md")
      out.push({ level: "warning", code: "lowercase-filename", id: f.name, file: at, message: `named ${nodePath.basename(f.file)} — found on macOS and Windows, missing on Linux; rename to SKILL.md` })
    if (f.parseError) {
      out.push({ level: "error", code: "unparseable", id: null, file: at, message: `${f.parseError} — the IRIS app drops this skill` })
      continue
    }
    if (!f.name) {
      out.push({ level: "error", code: "no-name", id: null, file: at, message: "no `name:` in the frontmatter — the IRIS app drops this skill" })
      continue
    }
    if (!isValidSkillId(f.name))
      out.push({ level: "error", code: "invalid-id", id: f.name, file: at, message: `"${f.name}" is not a portable skill id (lowercase letters, digits, hyphens, ≤64) — Claude Code will not load it` })
    if (f.description === undefined)
      out.push({ level: "error", code: "no-description", id: f.name, file: at, message: "no description — never offered to the model" })
    else if (f.description === null || !f.description.trim())
      out.push({ level: "error", code: "empty-description", id: f.name, file: at, message: "empty description — listed as a blank entry the model cannot choose on purpose" })
    else if (f.description.length > SKILL_DESCRIPTION_MAX)
      out.push({ level: "warning", code: "long-description", id: f.name, file: at, message: `description is ${f.description.length} characters (over ${SKILL_DESCRIPTION_MAX})` })
    const folder = nodePath.basename(f.rel)
    if (!f.rel.includes(nodePath.sep) && folder !== f.name)
      out.push({ level: "warning", code: "name-not-folder", id: f.name, file: at, message: `folder "${folder}" ≠ name "${f.name}" — the IRIS app calls it "${f.name}", Claude Code calls it "${folder}"` })
    if (isOrphanReplica(f, keep))
      out.push({ level: "error", code: "orphan", id: f.name, file: at, message: `generated from ${sourcePlaybookFor(f.root.dir, f.rel)}, which no longer exists — run: iris playbook sync` })
    const list = byId.get(f.name) ?? []
    list.push(f)
    byId.set(f.name, list)
  }
  for (const [id, list] of byId) {
    if (list.length < 2) continue
    const distinct = new Set(list.map((f) => f.sha)).size
    const where = list.map((f) => f.root.label).join(", ")
    if (distinct > 1)
      out.push({
        level: "error",
        code: "shadowed",
        id,
        file: list[list.length - 1].file,
        message: `${list.length} different copies (${where}) — IRIS app ≤1.18.117 loads one at random each start; Claude Code prefers ~/.claude/skills; the IRIS CLI prefers the project`,
      })
    else out.push({ level: "info", code: "shadowed-identical", id, file: list[0].file, message: `${list.length} identical copies (${where})` })
  }
  return out
}

/**
 * Remove generated replicas in `skillsDir` whose playbook is gone. Hand-written skills, symlinked
 * folders and anything in `keep` are never touched. Returns the folders removed.
 */
export function pruneOrphanReplicas(skillsDir: string, keep: Set<string>, parse: (src: string) => any = parseFrontmatter): string[] {
  const root: SkillRoot = { label: skillsDir, dir: skillsDir }
  const removed: string[] = []
  let entries: string[] = []
  try {
    entries = readdirSync(skillsDir)
  } catch {
    return removed
  }
  for (const e of entries) {
    const file = nodePath.join(skillsDir, e, "SKILL.md")
    if (!existsSync(file)) continue
    const f = readSkillFile(file, root, parse)
    if (!isOrphanReplica(f, keep)) continue
    const dir = nodePath.dirname(file)
    // Only the file we generated; anything else in the folder (scripts, references) belongs to someone.
    unlinkSync(file)
    try {
      if (readdirSync(dir).length === 0) rmdirSync(dir)
    } catch {}
    removed.push(e)
  }
  return removed
}

export type RemoveResult = "removed" | "absent" | "hand-written" | "symlink"

/** Remove ONE generated replica (uninstall). Never a hand-written skill, never through a symlink. */
export function removeGeneratedReplica(skillsDir: string, id: string): RemoveResult {
  const dir = nodePath.join(skillsDir, id)
  const file = nodePath.join(dir, "SKILL.md")
  try {
    if (lstatSync(dir).isSymbolicLink()) return "symlink"
  } catch {
    return "absent"
  }
  if (!existsSync(file)) return "absent"
  let text = ""
  try {
    text = readFileSync(file, "utf8")
  } catch {}
  if (!text.includes(SKILL_GENERATED_MARKER_TEXT)) return "hand-written"
  unlinkSync(file)
  try {
    if (readdirSync(dir).length === 0) rmdirSync(dir)
  } catch {}
  return "removed"
}
