const str = (v: unknown) => (v === null || v === undefined ? "" : String(v))

/** "12,34" → ["12","34"]. Agent ids are the numbers `iris agents list` shows. */
export function parseAgentIds(v: string | number | Array<string | number> | undefined | null): { ids: string[] } | { error: string } {
  const parts = (Array.isArray(v) ? v : [v ?? ""]).flatMap((x) => String(x).split(","))
  const ids = parts.map((x) => x.trim()).filter(Boolean)
  const bad = ids.find((x) => !/^[1-9][0-9]*$/.test(x))
  if (bad !== undefined) return { error: `"${bad}" is not an agent id — use the numbers \`iris agents list\` shows.` }
  return { ids: [...new Set(ids)] }
}

/**
 * POST /api/threads body for a room with agents (and optionally a live session).
 * The lead is always one of the agents — named on its own, it joins too. Agents answer when
 * @mentioned unless `alwaysOn`; a shared session always receives (it is someone's live chat).
 */
export function createRoomBody(o: {
  name: string
  agents?: string[]
  lead?: string | null
  sessionId?: string | null
  alwaysOn?: boolean
}): { name: string; agent_ids: string[]; agent_roles: string[]; auto_respond: boolean[] } | { error: string } {
  const lead = o.lead ? String(o.lead).trim() : null
  if (lead !== null && !/^[1-9][0-9]*$/.test(lead)) return { error: `"${o.lead}" is not an agent id.` }
  const agents = [...(o.agents ?? [])]
  if (lead && !agents.includes(lead)) agents.unshift(lead)
  const ids: string[] = []
  const roles: string[] = []
  const auto: boolean[] = []
  if (o.sessionId) {
    ids.push(sessionParticipantId(o.sessionId))
    roles.push("participant")
    auto.push(true)
  }
  for (const a of agents) {
    ids.push(a)
    roles.push(a === lead ? "lead" : "participant")
    auto.push(o.alwaysOn === true)
  }
  if (!ids.length) return { error: "A room needs someone in it: --agents <id,id> (your IRIS agents) and/or --session <id> (a live chat)." }
  return { name: o.name, agent_ids: ids, agent_roles: roles, auto_respond: auto }
}

export type RoomAgent = { id: string; name: string; role: string; alwaysOn: boolean }
export type RoomChain = { depth: number; turns: number; maxTurns: number; maxHops: number }
export type RoomPerson = { name: string; away: boolean; typing: boolean }

/** A cloud agent in GET /api/threads/{id} → thread.agents[] (role and always-on ride on `pivot`). */
export function readRoomAgent(a: any): RoomAgent {
  return {
    id: str(a?.id),
    name: str(a?.name) || `agent ${str(a?.id)}`,
    role: str(a?.pivot?.role ?? a?.role) || "participant",
    alwaysOn: Boolean(a?.pivot?.auto_respond ?? a?.auto_respond),
  }
}

/** `chain` from GET /api/threads/{id}: agents handing work to each other right now, or null. */
export function readRoomChain(c: any): RoomChain | null {
  if (!c || typeof c !== "object") return null
  const n = (v: unknown) => (typeof v === "number" && Number.isFinite(v) ? v : 0)
  return { depth: n(c.depth), turns: n(c.turns), maxTurns: n(c.max_turns), maxHops: n(c.max_hops) }
}

/** One entry of `present` (show, presence, list activity). */
export function readRoomPerson(p: any): RoomPerson {
  return { name: str(p?.name) || "Someone", away: p?.state === "background", typing: p?.typing === true }
}

/** What `iris workspace watch` draws from GET /api/threads/{id}. */
export function readRoomView(body: any): {
  id: string
  name: string
  project: string | null
  agents: RoomAgent[]
  chain: RoomChain | null
  present: RoomPerson[]
} {
  const t = body?.thread ?? {}
  return {
    id: str(t.id),
    name: str(t.name) || "Room",
    project: body?.project?.name ? str(body.project.name) : null,
    agents: (Array.isArray(t.agents) ? t.agents : []).map(readRoomAgent),
    chain: readRoomChain(body?.chain),
    present: (Array.isArray(body?.present) ? body.present : []).map(readRoomPerson),
  }
}

/** One row of GET /api/threads (`rooms`): its sessions, agents and what the list shows (#194490). */
export function readRoomRow(t: any): {
  id: string
  name: string
  sessions: string[]
  agents: RoomAgent[]
  messages: number | null
  present: RoomPerson[]
  unread: number
  working: boolean
  last: string | null
} {
  const a = t?.activity && typeof t.activity === "object" ? t.activity : {}
  const l = a.last && typeof a.last === "object" ? a.last : null
  const who = l ? (l.is_you === true ? "you" : str(l.kind === "agent" ? l.host_name : l.name) || "someone") : ""
  return {
    id: str(t?.id),
    name: str(t?.name),
    sessions: roomSessions(t?.participants),
    agents: (Array.isArray(t?.agents) ? t.agents : []).map(readRoomAgent),
    messages: typeof t?.messages_count === "number" ? t.messages_count : null,
    present: (Array.isArray(a.present) ? a.present : []).map(readRoomPerson),
    unread: Math.max(0, Number(a.unread) || 0),
    working: a.working === true,
    last: l ? `${who}: ${str(l.text) || str(l.tool)}`.slice(0, 120) : null,
  }
}

/** The participant in an add/update-agent response. */
export function readParticipant(body: any): { agentId: string; role: string; alwaysOn: boolean } | null {
  const p = body?.participant
  if (!p || typeof p !== "object") return null
  return { agentId: str(p.agent_id), role: str(p.role) || "participant", alwaysOn: p.auto_respond === true }
}

/** "agents are talking · 3 of 6" — or null when no hand-off is running. */
export function chainLine(c: RoomChain | null): string | null {
  if (!c) return null
  return c.maxTurns > 0 ? `agents are talking · ${c.turns} of ${c.maxTurns}` : `agents are talking · ${c.turns}`
}

/** "here: Flo (typing…), Alex (away)" — or null when nobody is. */
export function presentLine(people: RoomPerson[]): string | null {
  if (!people.length) return null
  return "here: " + people.map((p) => `${p.name}${p.typing ? " (typing…)" : p.away ? " (away)" : ""}`).join(", ")
}

/** One line per agent: who leads, who answers everything, who waits for an @mention. */
export function agentLines(agents: RoomAgent[]): string[] {
  const sorted = [...agents].sort((a, b) => Number(b.role === "lead") - Number(a.role === "lead"))
  return sorted.map((a) =>
    a.role === "lead"
      ? `${a.name} — lead (takes your request first, hands parts to the others)`
      : `${a.name} — ${a.alwaysOn ? "answers everything" : "answers when @mentioned"}${a.role !== "participant" ? ` · ${a.role}` : ""}`,
  )
}

/** PATCH /api/threads/{id}/agents/{agent} body — only what was asked for. */
export function roleUpdateBody(o: { role?: string | null; alwaysOn?: boolean | null }): Record<string, unknown> {
  const b: Record<string, unknown> = {}
  if (o.role) b.role = o.role
  if (typeof o.alwaysOn === "boolean") b.auto_respond = o.alwaysOn
  return b
}
