#!/usr/bin/env bun
/**
 * Copy the book (#193064) from fl-iris-api into this package as command-book.json.
 *
 *   bun script/sync-command-book.ts <path to fl-iris-api/config/cli-commands.yaml>
 *   bun script/sync-command-book.ts --ref <fl-iris-api git ref>      # via gh api, default: main
 *
 * The book is the one list; this is its generated copy, embedded so the binary carries it. A CLI command
 * missing from the book fails test/mcp/command-book.test.ts: declare it in fl-iris-api, then re-run this.
 */
import { join } from "path"

const args = process.argv.slice(2)
const refAt = args.indexOf("--ref")
let text: string
let source: string
if (refAt < 0 && args[0]) {
  text = await Bun.file(args[0]).text()
  source = args[0]
} else {
  const ref = refAt >= 0 ? args[refAt + 1] : "main"
  const out = Bun.spawnSync(["gh", "api", `repos/FREELABEL/fl-iris-api/contents/config/cli-commands.yaml?ref=${ref}`, "-H", "Accept: application/vnd.github.raw"])
  if (out.exitCode !== 0) throw new Error(`gh api failed: ${out.stderr.toString()}`)
  text = out.stdout.toString()
  source = `FREELABEL/fl-iris-api@${ref}:config/cli-commands.yaml`
}
const book = (Bun as any).YAML.parse(text) as {
  unclassified_ceiling: number
  commands: Record<string, { effect: string; actions?: Record<string, string> }>
}
const names = Object.keys(book.commands).sort()
const commands = Object.fromEntries(names.map((k) => [k, book.commands[k].effect]))
// For a command whose action is an argument (`hive tasks create`): the effect of each action.
const actions = Object.fromEntries(names.filter((k) => book.commands[k].actions).map((k) => [k, book.commands[k].actions]))
const copy = {
  generated_note: "GENERATED by script/sync-command-book.ts from the book in fl-iris-api — do not edit; edit config/cli-commands.yaml there.",
  source,
  unclassified_ceiling: book.unclassified_ceiling,
  commands,
  actions,
}
await Bun.write(join(import.meta.dir, "..", "command-book.json"), JSON.stringify(copy, null, 1) + "\n")
console.log(`command-book.json: ${Object.keys(commands).length} commands from ${source}`)
