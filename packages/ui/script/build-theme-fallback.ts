#!/usr/bin/env bun
/**
 * Writes src/styles/theme-fallback.css — the colours the app paints before JavaScript runs (#194375).
 *
 * The theme provider injects the active theme's tokens at runtime. Until then (first paint, the boot
 * splash, a crashed bundle) the page uses this file. It used to be a hand copy of OC-2 that had drifted
 * from oc-2.json (324 values) and had no dark block for v2 at all. Now it is generated from the default
 * theme's JSON, so the static colours and the runtime colours are the same numbers.
 *
 *   bun run script/build-theme-fallback.ts           # write it
 *   bun run script/build-theme-fallback.ts --check   # exit 1 if it is stale (used by the unit test)
 *
 * Selectors use `html:root` so they outrank the layered OC-2 primitives in v2/styles/colors.css
 * (alpha ramps still live there) regardless of import order.
 */

import { resolveThemeVariant, themeToCss } from "../src/theme/resolve"
import { resolveThemeVariantV2, themeV2ToCss } from "../src/theme/v2/resolve"
import { DEFAULT_THEME_ID } from "../src/theme/default-id"
import type { DesktopTheme } from "../src/theme/types"

const out = import.meta.dir + "/../src/styles/theme-fallback.css"

export async function renderFallback() {
  const theme = (await Bun.file(
    `${import.meta.dir}/../src/theme/themes/${DEFAULT_THEME_ID}.json`,
  ).json()) as DesktopTheme
  const block = (mode: "light" | "dark", indent: string) => {
    const isDark = mode === "dark"
    const variant = theme[mode]
    const lines = [
      `color-scheme: ${mode};`,
      `--text-mix-blend-mode: ${isDark ? "plus-lighter" : "multiply"};`,
      ...themeToCss(resolveThemeVariant(variant, isDark)).split("\n"),
      ...themeV2ToCss(resolveThemeVariantV2(variant, isDark)).split("\n"),
    ]
    return lines.map((line) => indent + line.trim()).join("\n")
  }
  return `/* Generated by script/build-theme-fallback.ts from themes/${DEFAULT_THEME_ID}.json. Do not edit by hand:
   change the theme JSON and run \`bun run generate:fallback\`. */

html:root {
${block("light", "  ")}
}

@media (prefers-color-scheme: dark) {
  html:root:not([data-color-scheme="light"]) {
${block("dark", "    ")}
  }
}

html:root[data-color-scheme="dark"] {
${block("dark", "  ")}
}
`
}

if (import.meta.main) {
  const next = await renderFallback()
  if (process.argv.includes("--check")) {
    const current = await Bun.file(out).text().catch(() => "")
    if (current !== next) {
      console.error("theme-fallback.css is stale — run `bun run generate:fallback` in packages/ui")
      process.exit(1)
    }
    console.log("theme-fallback.css is current")
  } else {
    await Bun.write(out, next)
    console.log("Wrote theme-fallback.css from", DEFAULT_THEME_ID)
  }
}
